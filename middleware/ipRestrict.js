const ipaddr = require('ipaddr.js');
const constants = require('../config/constants');

// ALLOWED_SUBNET is a static config value — it never changes at
// runtime, so there's no reason to re-parse the CIDR string on
// every single request (this ran on literally every request that
// reached the app, including every static asset). Parse it once at
// module load instead; the actual per-request cost is now just the
// address parse + match, which is what should scale with traffic.
const [allowedRange, allowedBits] =
  ipaddr.parseCIDR(constants.ALLOWED_SUBNET);

function ipRestrict(req, res, next) {

  try {

    const ip = req.ip.replace(/^::ffff:/, '');

    const addr = ipaddr.parse(ip);


    if (addr.kind() !== allowedRange.kind()) {
      return res.status(403).json({
        error: 'IP family mismatch'
      });
    }


    if (addr.match([allowedRange, allowedBits])) {
      return next();
    }


    return res.status(403).json({
      error: 'Access denied'
    });


  } catch (e) {

    return res.status(403).json({
      error: 'Access denied'
    });

  }
}

// Trust X-Forwarded-For only when Express binds to loopback, which is the
// Caddy deployment: Caddy is the only thing that can connect to 127.0.0.1,
// so the header can only come from the local reverse proxy. 'loopback' makes
// Express trust a header only when the TCP peer is itself loopback, and then
// use the rightmost non-loopback address as req.ip. When Express binds to a
// WireGuard or public address directly, nothing is trusted and req.ip is the
// socket peer, so a client-supplied X-Forwarded-For has no effect.
//
// The Caddyfile generated by utils/tlsSetup.js must OVERWRITE the header
// (header_up X-Forwarded-For {remote_host}), not append to it, so the header
// holds only the address Caddy observed.
function trustProxySetting(host = constants.HOST) {
  return host === '127.0.0.1' ? 'loopback' : false;
}


module.exports = {
  ipRestrict,
  trustProxySetting
};