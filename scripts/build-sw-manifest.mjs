#!/usr/bin/env node
// Generates public/sw-manifest.js: the list of application-shell files (with
// SHA-256 content hashes) that public/sw.js precaches, plus a version derived
// from those hashes.
//
//   node scripts/build-sw-manifest.mjs            write public/sw-manifest.js
//   node scripts/build-sw-manifest.mjs --check    exit 1 if it is out of date
//   node scripts/build-sw-manifest.mjs --dir ./public
//
// Run it on every deploy (before the files are uploaded/served). Any change to
// any shipped file changes the version, which changes sw-manifest.js, which is
// what makes browsers install the new Service Worker and replace the cache.
// Output is deterministic (no timestamps), so --check is safe in CI.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, relative, sep, extname, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const check = args.includes('--check');
const dirArg = args.indexOf('--dir');
const here = dirname(fileURLToPath(import.meta.url));
const publicDir = resolve(dirArg !== -1 ? args[dirArg + 1] : join(here, '..', 'public'));

// Static application assets only. Never user data, never the worker itself.
const INCLUDE_EXT = new Set(['.html', '.css', '.js', '.mjs', '.svg', '.png', '.jpg', '.jpeg', '.webp', '.gif', '.ico', '.woff', '.woff2', '.ttf']);
const EXCLUDE = new Set(['/sw.js', '/sw-manifest.js']);

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    if (e.name.startsWith('.')) return [];
    const full = join(dir, e.name);
    return e.isDirectory() ? walk(full) : [full];
  });
}

if (!existsSync(publicDir) || !statSync(publicDir).isDirectory()) {
  console.error(`public directory not found: ${publicDir}`);
  process.exit(2);
}

const files = walk(publicDir)
  .map((full) => '/' + relative(publicDir, full).split(sep).join('/'))
  .filter((url) => INCLUDE_EXT.has(extname(url).toLowerCase()) && !EXCLUDE.has(url))
  .sort()
  .map((url) => ({
    url,
    rev: createHash('sha256').update(readFileSync(join(publicDir, url))).digest('hex'),
  }));

if (!files.some((f) => f.url === '/index.html')) {
  console.error('/index.html is missing from the shell; refusing to generate a manifest.');
  process.exit(2);
}

const version = createHash('sha256')
  .update(files.map((f) => `${f.url}:${f.rev}`).join('\n'))
  .digest('hex')
  .slice(0, 12);

const out =
`// GENERATED by scripts/build-sw-manifest.mjs — do not edit by hand.
// Re-run it on every deploy; \`--check\` verifies it is current.
self.WIRE_SHELL = ${JSON.stringify({ version, files }, null, 1)};
`;

const target = join(publicDir, 'sw-manifest.js');

if (check) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('sw-manifest.js is out of date. Run: node scripts/build-sw-manifest.mjs');
    process.exit(1);
  }
  console.log(`sw-manifest.js is current (version ${version}, ${files.length} files)`);
} else {
  writeFileSync(target, out);
  const kb = files.reduce((n, f) => n + statSync(join(publicDir, f.url)).size, 0) / 1024;
  console.log(`sw-manifest.js written: version ${version}, ${files.length} files, ${kb.toFixed(0)} KB`);
}
