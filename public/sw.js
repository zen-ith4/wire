/* ==========================================================================
 * Wire — Service Worker
 *
 * Purpose: keep the *application itself* (HTML, JS, CSS, images) available
 * locally after the first load. It never stores user data.
 *
 * What it handles
 *   - Same-origin GET for a file listed in sw-manifest.js  -> precache, cache-first
 *   - Navigations to "/" or "/index.html"                   -> the precached shell
 *   - Google Fonts CSS (stale-while-revalidate) and font files (cache-first)
 *
 * What it deliberately never touches (the request goes straight to the
 * network, as if there were no worker)
 *   - anything under /api/, /socket.io/, uploads/downloads/media
 *   - every non-GET request, and any request with a Range header
 *   - any same-origin path that is not in the manifest
 *   - other cross-origin requests
 *
 * Versioning / updates
 *   sw-manifest.js (generated by scripts/build-sw-manifest.mjs) lists every
 *   shell file with a SHA-256. Its version is a hash of that list. The whole
 *   set is downloaded into a cache named for that version and each file is
 *   verified against its hash; if anything fails, the install fails and the
 *   previous version keeps working untouched. The new version replaces the old
 *   only after it is complete, and old caches are deleted on activation, so
 *   the page never runs a mix of old and new files.
 * ========================================================================== */

importScripts('/sw-manifest.js');

const SHELL = self.WIRE_SHELL;
const SHELL_CACHE = `wire-shell-${SHELL.version}`;
const FONT_CACHE = 'wire-fonts-v1';
const SHELL_URLS = new Set(SHELL.files.map((f) => f.url));
const INDEX = '/index.html';

const FONT_CSS_ORIGIN = 'https://fonts.googleapis.com';
const FONT_FILE_ORIGIN = 'https://fonts.gstatic.com';

// ---------------------------------------------------------------- install --

async function sha256Hex(buffer) {
  const digest = await crypto.subtle.digest('SHA-256', buffer);
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, '0')).join('');
}

async function precache() {
  const cache = await caches.open(SHELL_CACHE);

  await Promise.all(
    SHELL.files.map(async ({ url, rev }) => {
      // An interrupted earlier attempt at this same version may have stored
      // some files already; they were verified when stored.
      if (await cache.match(url)) return;

      // Bypass the HTTP cache: we must get what the server has *now*.
      const response = await fetch(new Request(url, { cache: 'reload' }));
      if (!response.ok) {
        throw new Error(`precache ${url}: HTTP ${response.status}`);
      }

      // Refuse to store anything that is not exactly what the manifest
      // describes (half-finished deploy, stale CDN edge, rewritten HTML...).
      // Better to keep the old version than to cache a mismatched file
      // under the new version number.
      const got = await sha256Hex(await response.clone().arrayBuffer());
      if (got !== rev) {
        throw new Error(`precache ${url}: content does not match the manifest`);
      }

      await cache.put(url, response);
    })
  );
}

self.addEventListener('install', (event) => {
  // No automatic skipWaiting(): the page decides when to switch (see
  // js/core/pwa.js), so a running session is never swapped mid-boot.
  event.waitUntil(precache());
});

// --------------------------------------------------------------- activate --

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keep = new Set([SHELL_CACHE, FONT_CACHE]);
      for (const key of await caches.keys()) {
        if (key.startsWith('wire-') && !keep.has(key)) {
          await caches.delete(key);
        }
      }
      await self.clients.claim();
    })()
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

// ------------------------------------------------------------------ fetch --

async function fromShell(path, request) {
  const cache = await caches.open(SHELL_CACHE);
  const hit = await cache.match(path);
  return hit || fetch(request); // should not happen after a complete install
}

async function staleWhileRevalidate(event, cacheName) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(event.request);

  const refresh = fetch(event.request)
    .then((response) => {
      if (response.ok || response.type === 'opaque') {
        cache.put(event.request, response.clone());
      }
      return response;
    })
    .catch(() => null);

  if (cached) {
    event.waitUntil(refresh);
    return cached;
  }
  return (await refresh) || Response.error();
}

async function cacheFirst(request, cacheName) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(request);
  if (cached) return cached;

  const response = await fetch(request);
  if (response.ok || response.type === 'opaque') {
    cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;

  // Only plain GETs. Writes, uploads and media/range requests are never ours.
  if (request.method !== 'GET' || request.headers.has('range')) return;

  const url = new URL(request.url);

  if (url.origin === self.location.origin) {
    if (request.mode === 'navigate') {
      if (url.pathname === '/' || url.pathname === INDEX) {
        event.respondWith(fromShell(INDEX, request));
      }
      return; // any other page is the server's business
    }

    if (SHELL_URLS.has(url.pathname) && !url.search) {
      event.respondWith(fromShell(url.pathname, request));
    }
    return; // /api, /socket.io, downloads, everything else: network
  }

  if (url.origin === FONT_CSS_ORIGIN) {
    event.respondWith(staleWhileRevalidate(event, FONT_CACHE));
  } else if (url.origin === FONT_FILE_ORIGIN) {
    event.respondWith(cacheFirst(request, FONT_CACHE));
  }
});
