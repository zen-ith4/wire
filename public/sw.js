/* ==========================================================================
 * Wire — Service Worker
 *
 * Purpose:
 *   Keep the application shell (HTML, JS, CSS and images) available locally
 *   after the first successful load.
 *
 * This worker NEVER stores user data.
 *
 * Handles:
 *   - Same-origin GET requests for files listed in sw-manifest.js
 *       -> cache-first
 *   - Navigation to "/" or "/index.html"
 *       -> precached application shell
 *   - Google Fonts CSS
 *       -> stale-while-revalidate
 *   - Google Fonts files
 *       -> cache-first
 *   - The opt-in encrypted DM media stream route
 *     (/__wire_media_stream/<id>), only for video/* and audio/*, only for a
 *     stream this worker knows and only for the client that registered it.
 *     The route is off unless MEDIA_STREAM_ENABLED is true.
 *
 * Deliberately untouched:
 *   - /api/
 *   - /socket.io/
 *   - uploads/downloads/media
 *   - all non-GET requests except the media route's HEAD
 *   - all requests with a Range header EXCEPT the media stream route
 *   - same-origin paths not present in the manifest
 *   - other cross-origin requests
 *
 * Media stream data:
 *   The media route holds the per-stream key and plaintext ONLY in worker
 *   memory. Nothing from that route is written to Cache Storage, IndexedDB,
 *   localStorage or a log. The registry is dropped when the worker is
 *   terminated, and the page re-handshakes.
 *
 * Versioning:
 *   sw-manifest.js is generated by scripts/build-sw-manifest.mjs.
 *
 *   Every shell file has:
 *     - its URL
 *     - its SHA-256 hash
 *
 *   The manifest version is derived from the complete file list.
 *
 *   sw-media-bundle.js is generated by scripts/build-sw-media-bundle.mjs,
 *   listed in sw-manifest.js and hash-verified at install time. The media route
 *   is OFF unless MEDIA_STREAM_ENABLED says otherwise.
 *
 *   A new worker installs into its own versioned cache. Every downloaded
 *   file is verified against its manifest hash before being stored.
 *
 *   If anything fails, installation fails and the currently active worker
 *   remains untouched.
 *
 *   After a successful install, the new worker activates immediately.
 *   The controlled application detects the controller change and reloads
 *   once so the new shell is used automatically.
 * ========================================================================== */

importScripts('/sw-manifest.js');

/*
 * Media bundle (Item 3, phase 3B).
 *
 * The bundle is generated by scripts/build-sw-media-bundle.mjs and is listed in
 * sw-manifest.js, so it is NOT a soft dependency: a missing or altered bundle
 * makes precache() fail, this worker's install is rejected, and the previously
 * active worker keeps serving (see precache()).
 *
 * The try/catch below covers exactly one case: the bundle exists, matches its
 * manifest hash and throws while it is evaluated. Then this worker activates
 * without a media bundle and the client falls back to the Blob path.
 *
 * The generated bundle publishes itself as the global `WireMedia`. This script
 * must therefore never declare a top-level `let`/`const` named `WireMedia`:
 * that would collide with the bundle's `var WireMedia` and the whole worker
 * script would fail to evaluate (measured, 8.2).
 */
try {
  importScripts('/sw-media-bundle.js');
} catch (error) {
  console.warn('[Wire SW] media bundle unavailable:', error);
}

/*
 * MEDIA STREAM ROUTE (Item 3, phase 3C).
 *
 * OFF by default. Flipping this constant is the ONLY way to enable the route,
 * and it is a one-line change in a tracked file: the feature can never be
 * turned on by a server response, a query parameter or a stale bundle.
 * public/sw.js is excluded from the manifest, so flipping it does NOT
 * invalidate the shell cache - only the worker itself is replaced.
 *
 * The route is implemented in C2: it registers a stream in worker memory,
 * serves the media URL's GET/HEAD ranges through the pure handler core, and
 * pulls a fresh media token from the page when one is needed. The flag must
 * never be baked into sw-media-bundle.js.
 */
const MEDIA_STREAM_ENABLED = false;
const MEDIA_STREAM_TOKEN_TIMEOUT_MS = 5000;
const MEDIA_STREAM_PATH = /^\/__wire_media_stream\/[A-Za-z0-9_-]{1,128}$/;
const MEDIA_STREAM_TOKEN_WAITERS = new Map();

const MEDIA_STREAM_REGISTRY = (() => {
  try {
    if (self.WireMedia && typeof self.WireMedia.createMediaStreamRegistry === 'function') {
      return self.WireMedia.createMediaStreamRegistry();
    }
  } catch {
    /* the bundle is optional; the route fails closed without it */
  }
  return null;
})();

const SHELL = self.WIRE_SHELL;

if (!SHELL || !SHELL.version || !Array.isArray(SHELL.files)) {
  throw new Error('Wire SW: invalid shell manifest');
}

const SHELL_CACHE = `wire-shell-${SHELL.version}`;
const FONT_CACHE = 'wire-fonts-v1';

const SHELL_URLS = new Set(
  SHELL.files.map(({ url }) => url)
);

const INDEX = '/index.html';

const FONT_CSS_ORIGIN = 'https://fonts.googleapis.com';
const FONT_FILE_ORIGIN = 'https://fonts.gstatic.com';


// ================================================================= install ==

async function sha256Hex(buffer) {
  const digest = await crypto.subtle.digest('SHA-256', buffer);

  return Array.from(
    new Uint8Array(digest),
    (byte) => byte.toString(16).padStart(2, '0')
  ).join('');
}


/**
 * Download and verify the complete application shell.
 *
 * Nothing from this version becomes active until the entire shell has
 * installed successfully.
 */
async function precache() {
  const cache = await caches.open(SHELL_CACHE);

  await Promise.all(
    SHELL.files.map(async ({ url, rev }) => {
      const existing = await cache.match(url);

      /*
       * Entries already written by this install were verified before
       * being stored. Reusing them allows an interrupted installation
       * to resume without downloading everything again.
       */
      if (existing) {
        return;
      }

      /*
       * Bypass the browser HTTP cache. The manifest represents the exact
       * deployment currently being installed.
       */
      const response = await fetch(
        new Request(url, {
          method: 'GET',
          cache: 'reload',
          credentials: 'same-origin'
        })
      );

      if (!response.ok) {
        throw new Error(
          `Wire SW: precache ${url}: HTTP ${response.status}`
        );
      }

      /*
       * Verify the actual bytes before storing them.
       */
      const body = await response.clone().arrayBuffer();
      const actualHash = await sha256Hex(body);

      if (actualHash !== rev) {
        throw new Error(
          `Wire SW: precache ${url}: content does not match manifest`
        );
      }

      await cache.put(url, response);
    })
  );
}


self.addEventListener('install', (event) => {
  /*
   * Important:
   *
   * Do NOT call skipWaiting() before precache() succeeds.
   *
   * If installation fails, this worker must never become active.
   */
  event.waitUntil(
    (async () => {
      try {
        await precache();

        /*
         * The entire shell is now verified and stored.
         *
         * Activate this worker immediately instead of waiting for all
         * existing tabs to close.
         */
        await self.skipWaiting();
      } catch (error) {
        console.error('[Wire SW] installation failed:', error);
        throw error;
      }
    })()
  );
});


// =============================================================== activate ==

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keep = new Set([
        SHELL_CACHE,
        FONT_CACHE
      ]);

      const cacheNames = await caches.keys();

      await Promise.all(
        cacheNames
          .filter(
            (name) =>
              name.startsWith('wire-') &&
              !keep.has(name)
          )
          .map((name) => caches.delete(name))
      );

      /*
       * Take control of currently open clients immediately.
       *
       * This causes controllerchange in the page.
       */
      await self.clients.claim();
    })()
  );
});

// ================================================================= helpers ==

async function fromShell(path, request) {
  const cache = await caches.open(SHELL_CACHE);
  const cached = await cache.match(path);

  if (cached) {
    return cached;
  }

  /*
   * This should only happen if something went unexpectedly wrong with
   * the install/cache. Falling back to the network is preferable to
   * returning an empty response.
   */
  return fetch(request);
}


/**
 * Stale-while-revalidate.
 *
 * Existing cached content is returned immediately while a fresh copy is
 * fetched in the background.
 */
async function staleWhileRevalidate(event, cacheName) {
  const cache = await caches.open(cacheName);
  const request = event.request;

  const cached = await cache.match(request);

  const refresh = fetch(request)
    .then(async (response) => {
      if (
        response.ok ||
        response.type === 'opaque'
      ) {
        await cache.put(
          request,
          response.clone()
        );
      }

      return response;
    })
    .catch(() => null);

  if (cached) {
    event.waitUntil(refresh);
    return cached;
  }

  const response = await refresh;

  return response || Response.error();
}


/**
 * Cache-first.
 *
 * Used for immutable-ish assets such as font files.
 */
async function cacheFirst(event, cacheName) {
  const cache = await caches.open(cacheName);
  const request = event.request;

  const cached = await cache.match(request);

  if (cached) {
    return cached;
  }

  const response = await fetch(request);

  if (
    response.ok ||
    response.type === 'opaque'
  ) {
    event.waitUntil(
      cache.put(
        request,
        response.clone()
      )
    );
  }

  return response;
}


// ============================================================ media route ==

function mediaStreamId(pathname) {
  const match = MEDIA_STREAM_PATH.exec(pathname);
  return match ? match[0].slice('/__wire_media_stream/'.length) : null;
}

function mediaBase64ToBytes(value, expectedLength) {
  if (typeof value !== 'string' || !value) return null;

  try {
    const binary = atob(value);
    if (binary.length !== expectedLength) return null;

    const bytes = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i += 1) {
      bytes[i] = binary.charCodeAt(i);
    }
    return bytes;
  } catch {
    return null;
  }
}

/**
 * The origin URL for a stream. It is derived from the registration fields,
 * never from the media element's URL or a query parameter.
 *
 * messageId is the DM message id of the attachment: the server route is
 * /api/dm/attachments/:messageId and the media token is bound to
 * (type 'dm', id = messageId) in middleware/mediaAuth.js. Only a plain
 * decimal id is accepted.
 */
function mediaTransportPath(data) {
  const messageId = String(data.messageId);
  if (!/^\d{1,20}$/.test(messageId)) return null;

  if (data.scope === 'dm') {
    return `/api/dm/attachments/${messageId}`;
  }

  // Item 3 is DM-only. A group scope is not a participant in this route,
  // so it is rejected rather than mapped to an untested path.
  return null;
}

function mediaErrorResponse(status, extra = {}) {
  return new Response(null, {
    status,
    headers: {
      'Cache-Control': 'no-store',
      'X-Content-Type-Options': 'nosniff',
      'Content-Security-Policy': 'sandbox',
      'Content-Length': '0',
      ...extra,
    },
  });
}

function responseFromPlan(plan, body = null) {
  return new Response(body, {
    status: plan.status,
    headers: plan.headers,
  });
}

async function sendClientMessage(clientId, message) {
  try {
    const client = await self.clients.get(clientId);
    if (!client) return false;
    client.postMessage(message);
    return true;
  } catch {
    return false;
  }
}

function settleTokenWaiter(streamId, ok) {
  const waiter = MEDIA_STREAM_TOKEN_WAITERS.get(streamId);
  if (!waiter) return;

  MEDIA_STREAM_TOKEN_WAITERS.delete(streamId);
  clearTimeout(waiter.timer);
  waiter.resolve(ok);
}

/**
 * Pull model: never use a page timer. If the current token is missing or
 * expired, ask the registering client once and hold this request for at most
 * five seconds. A second concurrent range request waits on the same promise,
 * so the page receives one TOKEN_NEEDED, not one per chunk.
 */
function waitForMediaToken(entry) {
  if (entry.token && Date.now() < entry.expiresAt) {
    return Promise.resolve(true);
  }

  const existing = MEDIA_STREAM_TOKEN_WAITERS.get(entry.streamId);
  if (existing) return existing.promise;

  let resolve;
  const promise = new Promise((done) => {
    resolve = done;
  });

  const timer = setTimeout(() => {
    const waiter = MEDIA_STREAM_TOKEN_WAITERS.get(entry.streamId);
    if (!waiter || waiter.resolve !== resolve) return;

    MEDIA_STREAM_TOKEN_WAITERS.delete(entry.streamId);
    if (MEDIA_STREAM_REGISTRY) {
      MEDIA_STREAM_REGISTRY.markDead(entry.streamId, 401);
    }
    void sendClientMessage(entry.clientId, {
      type: 'STREAM_DEAD',
      streamId: entry.streamId,
      reason: 'token-timeout',
    });
    resolve(false);
  }, MEDIA_STREAM_TOKEN_TIMEOUT_MS);

  MEDIA_STREAM_TOKEN_WAITERS.set(entry.streamId, { promise, resolve, timer });
  void sendClientMessage(entry.clientId, {
    type: 'TOKEN_NEEDED',
    streamId: entry.streamId,
  });

  return promise;
}

async function fetchMediaCiphertext(entry, plan) {
  const range = plan.ciphertextRange;
  if (!range) {
    if (plan.contentLength === 0) return new Uint8Array(0);
    throw new Error('media route has no ciphertext range');
  }

  const url = new URL(entry.path, self.location.origin);
  url.searchParams.set('token', entry.token);

  const init = {
    method: 'GET',
    headers: {
      Range: `bytes=${range.start}-${range.end}`,
    },
    cache: 'no-store',
    credentials: 'same-origin',
    redirect: 'error',
  };
  if (entry.abortController) init.signal = entry.abortController.signal;

  const response = await fetch(url.toString(), init);

  if (response.status === 401) {
    const error = new Error('media token rejected');
    error.mediaStatus = 401;
    throw error;
  }

  if (response.status === 403) {
    const error = new Error('media access forbidden');
    error.mediaStatus = 403;
    throw error;
  }

  if (response.status !== 206) {
    throw new Error(`media ciphertext fetch failed with ${response.status}`);
  }

  const expectedTotal = self.WireMedia.encryptedSizeFor(entry.plainSize);
  const contentRange = response.headers.get('content-range') || '';
  const match = /^bytes (\d+)-(\d+)\/(\d+)$/i.exec(contentRange);

  if (
    !match ||
    Number(match[1]) !== range.start ||
    Number(match[2]) !== range.end ||
    Number(match[3]) !== expectedTotal
  ) {
    throw new Error('media ciphertext range does not match the plan');
  }

  const ciphertext = new Uint8Array(await response.arrayBuffer());
  if (ciphertext.length !== range.end - range.start + 1) {
    throw new Error('media ciphertext length does not match the range');
  }

  return self.WireMedia.decryptMediaCiphertextRange({
    ciphertext,
    ciphertextRange: range,
    served: plan.served,
    totalSize: entry.plainSize,
    rawKey: entry.rawKey,
    baseIv: entry.baseIv,
  });
}

async function mediaStreamResponse(event, url) {
  const request = event.request;
  const streamId = mediaStreamId(url.pathname);

  if (!streamId || !MEDIA_STREAM_REGISTRY) {
    return mediaErrorResponse(404);
  }

  const entry = MEDIA_STREAM_REGISTRY.get(streamId);
  const clientMatches = Boolean(
    entry &&
    typeof event.clientId === 'string' &&
    event.clientId &&
    event.clientId === entry.clientId
  );

  if (!entry || !clientMatches) {
    return mediaErrorResponse(404);
  }

  if (entry.deadStatus) {
    return mediaErrorResponse(entry.deadStatus);
  }

  /*
   * Decide the non-token checks before waking the page. A script fetch or a
   * bad destination must fail 404 immediately, not hold a 5 s token wait.
   */
  const plan = self.WireMedia.planMediaResponse({
    method: request.method,
    destination: request.destination,
    streamKnown: true,
    clientMatches: true,
    authorized: true,
    mimeType: entry.mime,
    totalSize: entry.plainSize,
    rangeHeader: request.headers.get('range'),
  });

  if (plan.status !== 200 && plan.status !== 206) {
    return responseFromPlan(plan);
  }

  const authorized = await waitForMediaToken(entry);
  if (entry.deadStatus) {
    return mediaErrorResponse(entry.deadStatus);
  }
  if (!authorized) {
    return mediaErrorResponse(401);
  }

  if (plan.bodyMode === 'none' || plan.contentLength === 0) {
    return responseFromPlan(plan);
  }

  function killStream(status, reason) {
    if (MEDIA_STREAM_REGISTRY) {
      MEDIA_STREAM_REGISTRY.markDead(streamId, status);
    }
    void sendClientMessage(entry.clientId, {
      type: 'STREAM_DEAD',
      streamId,
      reason,
    });
    return mediaErrorResponse(status);
  }

  try {
    const body = await fetchMediaCiphertext(entry, plan);
    return responseFromPlan(plan, body);
  } catch (error) {
    if (error && error.mediaStatus === 403) {
      return killStream(403, 'forbidden');
    }

    if (error && error.mediaStatus === 401) {
      entry.token = null;
      entry.expiresAt = 0;
      const authorizedAgain = await waitForMediaToken(entry);
      if (entry.deadStatus) {
        return mediaErrorResponse(entry.deadStatus);
      }
      if (authorizedAgain) {
        try {
          const body = await fetchMediaCiphertext(entry, plan);
          return responseFromPlan(plan, body);
        } catch (retryError) {
          if (retryError && retryError.mediaStatus === 401) {
            return killStream(401, 'auth-failed');
          }
          if (retryError && retryError.mediaStatus === 403) {
            return killStream(403, 'forbidden');
          }
          return mediaErrorResponse(500);
        }
      }
      if (entry.deadStatus) {
        return mediaErrorResponse(entry.deadStatus);
      }
      return mediaErrorResponse(401);
    }
    return mediaErrorResponse(500);
  }
}

self.addEventListener('message', (event) => {
  if (!event || event.origin !== self.location.origin) return;

  const data = event.data;
  if (!data || typeof data !== 'object') return;

  if (data.type === 'MEDIA_STREAM_STATUS') {
    const reply = {
      type: 'MEDIA_STREAM_STATUS',
      enabled: MEDIA_STREAM_ENABLED,
      maxResponseChunks: self.WireMedia
        ? self.WireMedia.MEDIA_STREAM_MAX_RESPONSE_CHUNKS
        : 16,
      readAheadChunks: self.WireMedia
        ? self.WireMedia.ATTACHMENT_RANGE_READ_AHEAD_CHUNKS
        : 8,
    };
    const port = event.ports && event.ports[0];
    if (port && typeof port.postMessage === 'function') {
      port.postMessage(reply);
    } else if (event.source && typeof event.source.postMessage === 'function') {
      event.source.postMessage(reply);
    }
    return;
  }

  if (!MEDIA_STREAM_ENABLED || !MEDIA_STREAM_REGISTRY) return;

  const clientId = event.source && event.source.id;
  if (typeof clientId !== 'string' || !clientId) return;

  if (data.type === 'REGISTER_STREAM') {
    const path = mediaTransportPath(data);
    const rawKey = mediaBase64ToBytes(data.keyB64, 32);
    const baseIv = mediaBase64ToBytes(data.baseIvB64, 12);

    if (
      !path ||
      !rawKey ||
      !baseIv ||
      !Number.isInteger(data.plainSize) ||
      data.plainSize < 0
    ) {
      return;
    }

    settleTokenWaiter(data.streamId, false);
    try {
      MEDIA_STREAM_REGISTRY.register({
        streamId: data.streamId,
        clientId,
        messageId: data.messageId,
        scope: data.scope,
        groupId: data.groupId,
        path,
        rawKey,
        baseIv,
        mime: data.mime,
        plainSize: data.plainSize,
        abortController: new AbortController(),
      });
    } catch {
      /* malformed registration fails closed and stores nothing */
    }
    return;
  }

  if (data.type === 'UNREGISTER_STREAM') {
    if (typeof data.streamId !== 'string') return;
    settleTokenWaiter(data.streamId, false);
    MEDIA_STREAM_REGISTRY.unregister(data.streamId, clientId);
    return;
  }

  if (data.type === 'UPDATE_TOKEN') {
    if (typeof data.streamId !== 'string') return;
    if (MEDIA_STREAM_REGISTRY.updateToken(
      data.streamId,
      clientId,
      data.token,
      data.expiresAt
    )) {
      settleTokenWaiter(data.streamId, true);
    }
    return;
  }

  if (data.type === 'PURGE_CLIENT') {
    const target = typeof data.clientId === 'string' ? data.clientId : clientId;
    if (target !== clientId) return;

    for (const streamId of MEDIA_STREAM_REGISTRY.purgeClient(clientId)) {
      settleTokenWaiter(streamId, false);
    }
  }
});


// =================================================================== fetch ==

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);

  /*
   * MEDIA STREAM ROUTE (Item 3, phase 3C).
   *
   * This branch is deliberately BEFORE the "Range requests are never
   * intercepted" rule below: the media route answers Range requests itself.
   * With the flag OFF it returns immediately, so the request goes to the
   * network exactly as it did before this route existed.
   */
  if (
    url.origin === self.location.origin &&
    MEDIA_STREAM_PATH.test(url.pathname)
  ) {
    if (!MEDIA_STREAM_ENABLED) {
      return;
    }

    if (request.method !== 'GET' && request.method !== 'HEAD') {
      event.respondWith(mediaErrorResponse(405, { Allow: 'GET, HEAD' }));
      return;
    }

    event.respondWith(mediaStreamResponse(event, url));
    return;
  }

  /*
   * Only plain GET requests belong to this worker.
   */
  if (request.method !== 'GET') {
    return;
  }

  /*
   * Range requests are deliberately never intercepted, except the media
   * route handled above.
   */
  if (request.headers.has('range')) {
    return;
  }


  // -------------------------------------------------------- same-origin --

  if (url.origin === self.location.origin) {

    // ---------------------------------------------------------- navigation --

    if (request.mode === 'navigate') {

      /*
       * Only the actual application shell gets offline navigation support.
       */
      if (
        url.pathname === '/' ||
        url.pathname === INDEX
      ) {
        event.respondWith(
          fromShell(INDEX, request)
        );
      }

      return;
    }


    // --------------------------------------------------------- shell files --

    /*
     * Only exact manifest entries are handled.
     *
     * Query-string URLs intentionally bypass the shell cache.
     */
    if (
      !url.search &&
      SHELL_URLS.has(url.pathname)
    ) {
      event.respondWith(
        fromShell(url.pathname, request)
      );
    }

    /*
     * Everything else goes directly to the network.
     */
    return;
  }


  // ------------------------------------------------------ Google Fonts --

  if (url.origin === FONT_CSS_ORIGIN) {
    event.respondWith(
      staleWhileRevalidate(
        event,
        FONT_CACHE
      )
    );

    return;
  }


  if (url.origin === FONT_FILE_ORIGIN) {
    event.respondWith(
      cacheFirst(
        event,
        FONT_CACHE
      )
    );

    return;
  }

  /*
   * All other cross-origin requests remain completely untouched.
   */
});