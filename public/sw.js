/* ==========================================================================
 * Wire — Service Worker
 *
 * Purpose:
 *   Keep the application shell (HTML, JS, CSS and images) available locally
 *   after the first successful load.
 *
 * This worker NEVER stores user data.
 *
 * Handles:
 *   - Same-origin GET requests for files listed in sw-manifest.js
 *       -> cache-first
 *   - Navigation to "/" or "/index.html"
 *       -> precached application shell
 *   - Google Fonts CSS
 *       -> stale-while-revalidate
 *   - Google Fonts files
 *       -> cache-first
 *
 * Deliberately untouched:
 *   - /api/
 *   - /socket.io/
 *   - uploads/downloads/media
 *   - all non-GET requests
 *   - all requests with a Range header
 *   - same-origin paths not present in the manifest
 *   - other cross-origin requests
 *
 * Versioning:
 *   sw-manifest.js is generated by scripts/build-sw-manifest.mjs.
 *
 *   Every shell file has:
 *     - its URL
 *     - its SHA-256 hash
 *
 *   The manifest version is derived from the complete file list.
 *
 *   A new worker installs into its own versioned cache. Every downloaded
 *   file is verified against its manifest hash before being stored.
 *
 *   If anything fails, installation fails and the currently active worker
 *   remains untouched.
 *
 *   The new worker is NOT automatically activated. The application decides
 *   when it is safe to switch workers.
 * ========================================================================== */

importScripts('/sw-manifest.js');

const SHELL = self.WIRE_SHELL;

if (!SHELL || !SHELL.version || !Array.isArray(SHELL.files)) {
  throw new Error('Wire SW: invalid shell manifest');
}

const SHELL_CACHE = `wire-shell-${SHELL.version}`;
const FONT_CACHE = 'wire-fonts-v1';

const SHELL_URLS = new Set(
  SHELL.files.map(({ url }) => url)
);

const INDEX = '/index.html';

const FONT_CSS_ORIGIN = 'https://fonts.googleapis.com';
const FONT_FILE_ORIGIN = 'https://fonts.gstatic.com';


// ================================================================= install ==

async function sha256Hex(buffer) {
  const digest = await crypto.subtle.digest('SHA-256', buffer);

  return Array.from(
    new Uint8Array(digest),
    (byte) => byte.toString(16).padStart(2, '0')
  ).join('');
}


/**
 * Download and verify the complete application shell.
 *
 * Important:
 *   Nothing from this version becomes active until the entire shell has
 *   installed successfully.
 */
async function precache() {
  const cache = await caches.open(SHELL_CACHE);

  await Promise.all(
    SHELL.files.map(async ({ url, rev }) => {
      const existing = await cache.match(url);

      /*
       * Entries already written by this install were verified before they
       * were stored. Reusing them also allows an interrupted installation
       * to resume instead of downloading the entire shell again.
       */
      if (existing) {
        return;
      }

      /*
       * Bypass the browser HTTP cache. The manifest represents the exact
       * deployment currently being installed, so we need the server's
       * current bytes.
       */
      const response = await fetch(
        new Request(url, {
          method: 'GET',
          cache: 'reload',
          credentials: 'same-origin'
        })
      );

      if (!response.ok) {
        throw new Error(
          `Wire SW: precache ${url}: HTTP ${response.status}`
        );
      }

      /*
       * Verify the actual bytes before putting them into the versioned
       * cache. This protects against:
       *
       *   - incomplete deployments
       *   - stale CDN/proxy responses
       *   - rewritten HTML
       *   - manifest/server mismatches
       */
      const body = await response.clone().arrayBuffer();
      const actualHash = await sha256Hex(body);

      if (actualHash !== rev) {
        throw new Error(
          `Wire SW: precache ${url}: content does not match manifest`
        );
      }

      await cache.put(url, response);
    })
  );
}


self.addEventListener('install', (event) => {
  /*
   * Deliberately do NOT call skipWaiting() here.
   *
   * The currently running application remains on the old worker until
   * js/core/pwa.js decides that switching is safe.
   */
  event.waitUntil(
    precache().catch((error) => {
      console.error('[Wire SW] installation failed:', error);
      throw error;
    })
  );
});


// =============================================================== activate ==

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keep = new Set([
        SHELL_CACHE,
        FONT_CACHE
      ]);

      const cacheNames = await caches.keys();

      await Promise.all(
        cacheNames
          .filter(
            (name) =>
              name.startsWith('wire-') &&
              !keep.has(name)
          )
          .map((name) => caches.delete(name))
      );

      /*
       * Once activated, make this worker control currently open clients.
       */
      await self.clients.claim();
    })()
  );
});


// =============================================================== messaging ==

self.addEventListener('message', (event) => {
  if (
    event.data &&
    event.data.type === 'SKIP_WAITING'
  ) {
    self.skipWaiting();
  }
});


// ================================================================= helpers ==

async function fromShell(path, request) {
  const cache = await caches.open(SHELL_CACHE);
  const cached = await cache.match(path);

  if (cached) {
    return cached;
  }

  /*
   * This should only happen if something went unexpectedly wrong with the
   * install/cache. Falling back to the network is preferable to returning
   * an empty response.
   */
  return fetch(request);
}


/**
 * Stale-while-revalidate.
 *
 * Existing cached content is returned immediately while a fresh copy is
 * fetched in the background.
 */
async function staleWhileRevalidate(event, cacheName) {
  const cache = await caches.open(cacheName);
  const request = event.request;

  const cached = await cache.match(request);

  const refresh = fetch(request)
    .then(async (response) => {
      if (
        response.ok ||
        response.type === 'opaque'
      ) {
        await cache.put(
          request,
          response.clone()
        );
      }

      return response;
    })
    .catch(() => null);

  if (cached) {
    /*
     * Keep the background cache update alive even if the fetch handler
     * itself has already returned the cached response.
     */
    event.waitUntil(refresh);

    return cached;
  }

  /*
   * No cached copy exists. Wait for the network request.
   */
  const response = await refresh;

  return response || Response.error();
}


/**
 * Cache-first.
 *
 * Used for immutable-ish assets such as font files.
 */
async function cacheFirst(event, cacheName) {
  const cache = await caches.open(cacheName);
  const request = event.request;

  const cached = await cache.match(request);

  if (cached) {
    return cached;
  }

  const response = await fetch(request);

  if (
    response.ok ||
    response.type === 'opaque'
  ) {
    /*
     * Do not leave cache.put() as an untracked promise.
     *
     * The fetch response can be returned immediately, while waitUntil()
     * keeps the cache write alive for the lifetime of the event.
     */
    event.waitUntil(
      cache.put(
        request,
        response.clone()
      )
    );
  }

  return response;
}


// =================================================================== fetch ==

self.addEventListener('fetch', (event) => {
  const request = event.request;

  /*
   * Only plain GET requests belong to this worker.
   *
   * This automatically leaves:
   *   POST / PUT / PATCH / DELETE / etc.
   * untouched.
   */
  if (request.method !== 'GET') {
    return;
  }

  /*
   * Range requests are deliberately never intercepted.
   *
   * This is important for media/video/audio/download behavior.
   */
  if (request.headers.has('range')) {
    return;
  }

  const url = new URL(request.url);


  // -------------------------------------------------------- same-origin --

  if (url.origin === self.location.origin) {

    // ---------------------------------------------------------- navigation --

    if (request.mode === 'navigate') {

      /*
       * Only the actual application shell gets offline navigation support.
       *
       * Other paths remain the server's responsibility.
       */
      if (
        url.pathname === '/' ||
        url.pathname === INDEX
      ) {
        event.respondWith(
          fromShell(INDEX, request)
        );
      }

      return;
    }


    // --------------------------------------------------------- shell files --

    /*
     * Only exact manifest entries are handled.
     *
     * Query-string URLs intentionally bypass the shell cache because they
     * are not part of the manifest's canonical asset set.
     */
    if (
      !url.search &&
      SHELL_URLS.has(url.pathname)
    ) {
      event.respondWith(
        fromShell(url.pathname, request)
      );
    }

    /*
     * Everything else goes directly to the network:
     *
     *   /api/*
     *   /socket.io/*
     *   /media/*
     *   uploads/downloads
     *   unknown routes
     *   anything not present in the manifest
     */
    return;
  }


  // ------------------------------------------------------ Google Fonts --

  if (url.origin === FONT_CSS_ORIGIN) {
    event.respondWith(
      staleWhileRevalidate(
        event,
        FONT_CACHE
      )
    );

    return;
  }


  if (url.origin === FONT_FILE_ORIGIN) {
    event.respondWith(
      cacheFirst(
        event,
        FONT_CACHE
      )
    );

    return;
  }

  /*
   * All other cross-origin requests remain completely untouched.
   */
});